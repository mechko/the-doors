#!/bin/bash
set -euo pipefail

# Ensure a test user and a current one-hour test booking exist.

source .env

START=$(date +%s)
END=$((START+(60*60)))
TEST_USER="test"
TEST_PASSWORD_HASH='$2y$12$ic.RwL7wtTqI5Vfz/HgY3e7BfQfHSNd/uwBMZI3Viv5.LnWxvQcge'
TEST_BOOKING_NAME="The Doors Test Booking"

mysql \
  --host=127.0.0.1 \
  --port 3306 \
  --password="${MYSQL_PASSWORD:?MYSQL_PASSWORD must be set}" \
  -u "${MYSQL_USER:?MYSQL_USER must be set}" \
  "${MYSQL_DATABASE:?MYSQL_DATABASE must be set}" <<SQL
INSERT INTO mrbs_users (
  level,
  name,
  display_name,
  password_hash,
  email,
  last_login,
  reset_key_expiry
) VALUES (
  1,
  '${TEST_USER}',
  '${TEST_USER}',
  '${TEST_PASSWORD_HASH}',
  'test@example.invalid',
  0,
  0
) ON DUPLICATE KEY UPDATE
  display_name = VALUES(display_name),
  password_hash = VALUES(password_hash),
  email = VALUES(email);

SET @test_room_id := (
  SELECT id
  FROM mrbs_room
  WHERE disabled = 0
  ORDER BY (LOCATE('-', sort_key) > 0) DESC, id ASC
  LIMIT 1
);

SET @test_entry_id := (
  SELECT id
  FROM mrbs_entry
  WHERE create_by = '${TEST_USER}' AND name = '${TEST_BOOKING_NAME}'
  ORDER BY id ASC
  LIMIT 1
);

UPDATE mrbs_entry
SET
  start_time = ${START},
  end_time = ${END},
  room_id = @test_room_id,
  modified_by = '${TEST_USER}',
  description = 'Generated by update-test-booking.sh'
WHERE id = @test_entry_id
  AND @test_entry_id IS NOT NULL;

INSERT INTO mrbs_entry (
  start_time,
  end_time,
  entry_type,
  repeat_id,
  room_id,
  create_by,
  modified_by,
  name,
  type,
  description,
  status,
  ical_uid,
  ical_sequence,
  allow_registration,
  registrant_limit,
  registrant_limit_enabled,
  registration_opens,
  registration_opens_enabled,
  registration_closes,
  registration_closes_enabled
)
SELECT
  ${START},
  ${END},
  0,
  NULL,
  @test_room_id,
  '${TEST_USER}',
  '${TEST_USER}',
  '${TEST_BOOKING_NAME}',
  'I',
  'Generated by update-test-booking.sh',
  0,
  CONCAT('THE-DOORS-TEST-', UNIX_TIMESTAMP(), '@localhost'),
  0,
  0,
  0,
  1,
  1209600,
  0,
  0,
  0
WHERE @test_entry_id IS NULL
  AND NOT EXISTS (
    SELECT 1
    FROM mrbs_entry
    WHERE create_by = '${TEST_USER}' AND name = '${TEST_BOOKING_NAME}'
  );

SELECT
  u.name AS user_name,
  e.id AS booking_id,
  e.start_time,
  e.end_time,
  e.room_id,
  r.room_name,
  CASE
    WHEN LOCATE('-', r.sort_key) > 0 THEN SUBSTRING_INDEX(r.sort_key, '-', -1)
    ELSE ''
  END AS lock_id
FROM mrbs_users u
JOIN mrbs_entry e ON e.create_by = u.name
JOIN mrbs_room r ON r.id = e.room_id
WHERE u.name = '${TEST_USER}'
  AND e.name = '${TEST_BOOKING_NAME}'
ORDER BY e.id ASC
LIMIT 1;
SQL
